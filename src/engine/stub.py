"""Stand-ins that keep the skeleton runnable before the real engine lands.

Nothing here computes statistics. The numbers come from the committed stub set
under `data/stub/`, generated by `scripts/generate_stub_data.py`. Delete each
function once the ticket named in its docstring replaces it.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any

from .discovery import SessionHistory


def select_first_eligible(
    candidates: Sequence[dict[str, Any]],
    history: SessionHistory,
) -> dict[str, Any] | None:
    """Stands in for `engine.discovery.select_surprise` (ticket #9).

    Takes the highest-scoring Candidate that is headline eligible and shares no
    Region with anything already shown. The real version draws at random from
    the top N.
    """
    for candidate in candidates:
        if not candidate["headline_eligible"]:
            continue
        if candidate["discovery_id"] in history.shown_discovery_ids:
            continue
        if any(region_id in history.shown_region_ids for region_id in candidate["region_ids"]):
            continue
        return candidate
    return None
